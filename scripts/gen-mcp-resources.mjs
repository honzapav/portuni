// Regenerates apps/server/mcp/resources/resources-text.ts from the .md
// sources next to it. Run after editing any of those .md files:
//
//   node scripts/gen-mcp-resources.mjs
//
// Why generated instead of read at runtime (#255): the sidecar is compiled
// with `bun build --compile` (scripts/build-sidecar.mjs), which only
// bundles what is statically imported -- a runtime readFile(new URL(...,
// import.meta.url)) for a file nothing imports resolves to the virtual
// /$bunfs/root/ path inside the compiled binary, which does not exist
// there. A plain string-constant module, by contrast, is compiled/bundled
// identically by tsc+node, tsx and bun --compile: one code path, no
// runtime file I/O, no separate embedding API for the bun target.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join, basename } from "node:path";
import { fileURLToPath } from "node:url";

const resourcesDir = dirname(fileURLToPath(import.meta.url)).replace(
  /\/scripts$/,
  "/apps/server/mcp/resources",
);

const mdFiles = readdirSync(resourcesDir)
  .filter((f) => f.endsWith(".md"))
  .sort();

function constName(filename) {
  return (
    basename(filename, ".md")
      .toUpperCase()
      .replace(/-/g, "_") + "_MD"
  );
}

const exports = mdFiles.map((f) => {
  const content = readFileSync(join(resourcesDir, f), "utf8");
  return `export const ${constName(f)} = ${JSON.stringify(content)};\n`;
});

const header = `// AUTO-GENERATED by scripts/gen-mcp-resources.mjs from the .md files in
// this directory -- do not hand-edit. Run \`node scripts/gen-mcp-resources.mjs\`
// after changing any of them (a stale copy here fails
// test/mcp-resources.test.ts).
//
// See that script's header comment for why this is generated instead of
// read from disk at runtime.

`;

writeFileSync(join(resourcesDir, "resources-text.ts"), header + exports.join("\n"));
console.log(`wrote ${join(resourcesDir, "resources-text.ts")} from ${mdFiles.length} source file(s)`);
